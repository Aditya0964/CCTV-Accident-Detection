"""Phase 2 CLI: Compute speed drop, direction change, interaction, and anomaly candidates."""

from __future__ import annotations

import argparse
from pathlib import Path

from src.clip_buffer import extract_candidate_clips, render_anomaly_video
from src.motion_anomaly import (
    AnomalyConfig,
    analyze_motion_anomalies,
    load_tracks_csv,
    write_candidates_json,
    write_motion_scores_csv,
)


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--tracks",
        type=Path,
        default=Path("outputs/tracks.csv"),
        help="Input tracks.csv generated by Phase 1",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("outputs"),
        help="Directory for motion_scores.csv, candidates.json, and clips",
    )
    parser.add_argument(
        "--video",
        type=Path,
        default=None,
        help="Optional source CCTV video (required for --extract-clips or --render-video)",
    )
    parser.add_argument(
        "--width",
        type=int,
        default=960,
        help="Resize width matching Phase 1 tracking coordinates",
    )
    parser.add_argument(
        "--fps",
        type=float,
        default=None,
        help="Override video FPS (inferred from tracks.csv when omitted)",
    )
    parser.add_argument(
        "--mode",
        choices=["full", "motion_only"],
        default="full",
        help="Scoring mode: 'full' (0-9) or 'motion_only' (speed + direction ablation)",
    )
    parser.add_argument("--speed-drop-ratio", type=float, default=0.25)
    parser.add_argument("--min-prev-speed", type=float, default=25.0)
    parser.add_argument("--angle-deg", type=float, default=50.0)
    parser.add_argument("--proximity-norm", type=float, default=1.25)
    parser.add_argument("--iou-threshold", type=float, default=0.05)
    parser.add_argument("--stationary-speed", type=float, default=15.0)
    parser.add_argument("--candidate-threshold", type=int, default=None)
    parser.add_argument("--merge-window-sec", type=float, default=5.0)
    parser.add_argument("--clip-before-sec", type=float, default=2.0)
    parser.add_argument("--clip-after-sec", type=float, default=2.0)
    parser.add_argument(
        "--extract-clips",
        action="store_true",
        help="Extract [t - 2s, t + 2s] candidate video clips and peak keyframes",
    )
    parser.add_argument(
        "--render-video",
        action="store_true",
        help="Render annotated anomaly preview video (anomaly_preview.mp4)",
    )
    return parser.parse_args(argv)


def run(args: argparse.Namespace) -> None:
    if (args.extract_clips or args.render_video) and args.video is None:
        raise ValueError("--video is required when --extract-clips or --render-video is set")

    observations = load_tracks_csv(args.tracks)
    config = AnomalyConfig(
        fps=args.fps,
        mode=args.mode,
        speed_drop_ratio=args.speed_drop_ratio,
        min_prev_speed_px_s=args.min_prev_speed,
        direction_change_deg=args.angle_deg,
        proximity_norm_threshold=args.proximity_norm,
        iou_threshold=args.iou_threshold,
        stationary_speed_px_s=args.stationary_speed,
        candidate_threshold=args.candidate_threshold,
        merge_window_sec=args.merge_window_sec,
        clip_before_sec=args.clip_before_sec,
        clip_after_sec=args.clip_after_sec,
    )

    frame_scores, candidates = analyze_motion_anomalies(observations, config)

    args.output_dir.mkdir(parents=True, exist_ok=True)
    scores_csv = args.output_dir / "motion_scores.csv"
    candidates_json = args.output_dir / "candidates.json"
    write_motion_scores_csv(frame_scores, scores_csv)

    if args.video is not None and args.extract_clips and candidates:
        extract_candidate_clips(
            video_path=args.video,
            candidates=candidates,
            output_dir=args.output_dir,
            target_width=args.width,
            before_sec=args.clip_before_sec,
            after_sec=args.clip_after_sec,
        )

    if args.video is not None and args.render_video:
        preview_path = args.output_dir / "anomaly_preview.mp4"
        render_anomaly_video(
            video_path=args.video,
            frame_scores=frame_scores,
            candidates=candidates,
            output_path=preview_path,
            target_width=args.width,
        )
        print(f"Anomaly preview video: {preview_path}")

    write_candidates_json(candidates, candidates_json)
    print(f"Analyzed {len(frame_scores)} tracked observations -> {len(candidates)} candidate(s)")
    print(f"Motion scores CSV: {scores_csv}")
    print(f"Candidates JSON: {candidates_json}")


if __name__ == "__main__":
    run(parse_args())
